#!/usr/bin/env bash
# Regenerate the crate table at the end of THIRD_PARTY.md from Cargo.lock
# (normal dependencies, all targets, all features). Run after dependency changes.
set -euo pipefail
cd "$(dirname "$0")/.."
marker='<!-- crates: generated by packaging/third-party.sh -->'
head=$(awk -v m="$marker" '{print} $0==m{exit}' THIRD_PARTY.md)
{
  printf '%s\n\n| Crate | Version | License |\n|---|---|---|\n' "$head"
  cargo tree -e normal --prefix none --target all --all-features -f '{p}|{l}' |
    sed 's/ (proc-macro)//; s/ (\*)//; s/ ([^)]*)|/|/' | sort -u |
    awk -F'|' '{split($1,a," "); if (a[1]!="grokbot-tui") printf "| %s | %s | %s |\n", a[1], substr(a[2],2), $2}'
} > THIRD_PARTY.md.new
mv THIRD_PARTY.md.new THIRD_PARTY.md
